// Writes src/styles/app-themes.css: one [data-theme='<id>'] block of --nish-*
// colors per Nishboard preset, derived by src/lib/themeVars.ts from the colors in
// src/lib/appPresets.ts. Run with `pnpm --filter @dash/renderer gen:themes`
// (plain Node — type stripping — no build step). Commit the output.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_PRESETS } from '../src/lib/appPresets.ts';
import { contrast, deriveThemeColors, toCssVars } from '../src/lib/themeVars.ts';

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/styles/app-themes.css');
const parts = ['/* Generated by scripts/gen-app-themes.ts from src/lib/appPresets.ts. Do not edit. */', ''];

for (const preset of APP_PRESETS) {
  const colors = deriveThemeColors(preset.base);
  // Same bar as @nish/ui's own themes: body text tiers stay readable on panels.
  for (const role of ['hi', 'hi2', 'hi3', 'accent', 'ok', 'loss', 'warn', 'info'] as const) {
    const worst = Math.min(contrast(colors[role], colors.surface), contrast(colors[role], colors.elevated));
    if (worst < 4.5) throw new Error(`${preset.id}: ${role} ${colors[role]} is ${worst.toFixed(2)}:1`);
  }
  const vars = Object.entries(toCssVars(colors)).map(([k, v]) => `  ${k}: ${v};`);
  parts.push(`[data-theme='${preset.id}'] {`, `  color-scheme: ${preset.base.scheme};`, ...vars, '}', '');
}

writeFileSync(out, parts.join('\n'));
console.log(`wrote ${APP_PRESETS.length} presets → ${out}`);
